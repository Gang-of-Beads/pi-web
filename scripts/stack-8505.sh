#!/usr/bin/env bash
#
# An isolated dev stack on port 8505: one command to build it, restart it, and
# prove it is up.
#
# It runs with its own data dir, so it never touches a PI WEB you already run on
# 8504 with the default data dir, and this script must never be able to touch
# that one. So it never kills by process name: a process is an 8505 process
# only when its command line - argv plus environment, as `ps -E` prints it on macOS and
# /proc/<pid>/cmdline plus /proc/<pid>/environ give it on Linux - contains an
# exact match for this stack's data dir, its socket path, or PI_WEB_PORT=8505.
# Anything listening on 8505 without one of those markers is reported and left
# alone, and the script exits non-zero rather than guessing. Ancestors of this
# script are refused as well, so the session daemon hosting whoever runs this
# cannot be stopped by it.
#
# Usage:
#   scripts/stack-8505.sh up [--skip-build]   build, restart, wait for HTTP 200
#   scripts/stack-8505.sh down                stop this stack only
#   scripts/stack-8505.sh status              PIDs and health, no changes
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PORT=8505
DATA_DIR="${PI_WEB_8505_DATA_DIR:-$HOME/.pi-web-8505}"
SOCKET="$DATA_DIR/sessiond.sock"
SESSIOND_TMUX=pi-web-8505-sessiond
WEB_TMUX=pi-web-8505-web
BASE_URL="http://127.0.0.1:$PORT"
READY_TIMEOUT_SECONDS=120
# The user config (~/.config/pi-web/config.json) is shared with 8504 and may be
# read-only (generated by a configuration manager). PI_WEB_8505_CONFIG points
# this stack at its own writable copy, so Settings saves can be exercised
# without touching 8504's.
CONFIG_ENV="${PI_WEB_8505_CONFIG:+PI_WEB_CONFIG=$PI_WEB_8505_CONFIG }"
# The pi agent dir (~/.pi/agent) is shared with 8504 too: session files, settings,
# trust and accounts. Sessions this stack writes land in pi's shared session store,
# so an 8504 project that contains the seed workspace (one rooted at $HOME) lists
# them, and 8504 can open the same file this stack has open (2026-10-13). Set
# PI_WEB_8505_AGENT_DIR to give this stack its own agent dir.
AGENT_ENV="${PI_WEB_8505_AGENT_DIR:+PI_CODING_AGENT_DIR=$PI_WEB_8505_AGENT_DIR }"

usage() {
  awk 'NR == 1 { next } /^#/ { sub(/^# ?/, ""); print; next } { exit }' "${BASH_SOURCE[0]}"
}

# Linux procps has no `ps -E`; /proc holds the same two lists, NUL-separated.
has_proc() {
  [ -d /proc/self ]
}

# argv + environment of one process, one record per line, which is where the
# 8505 markers are: they are set as environment for `node`, so argv alone would
# not show them. /proc keeps each record whole, so a variable whose value merely
# contains a marker cannot pass for the marker; `ps -E` prints one line, which
# only spaces can split.
process_records() {
  if has_proc; then
    [ -r "/proc/$1/environ" ] || return 0
    { tr '\0' '\n' <"/proc/$1/cmdline"; printf '\n'; tr '\0' '\n' <"/proc/$1/environ"; } 2>/dev/null || true
    return 0
  fi
  { ps -p "$1" -Eww -o command= 2>/dev/null || true; } | tr ' ' '\n'
}

process_command_line() {
  process_records "$1" | { grep -v '^$' || true; } | tr '\n' ' '
}

# The guard. Membership of this stack is an exact token match, never a name.
# macOS `ps -E` omits the environment for daemonised children (measured: only
# the bash wrapper matched, the node processes did not), so a second membership
# proof exists: HOLDING this stack's socket or port while running this repo's
# server entrypoint. Resource ownership plus code identity - still never a name.
is_8505_process() {
  if process_records "$1" | grep -Fx \
    -e "PI_WEB_DATA_DIR=$DATA_DIR" \
    -e "PI_WEB_SESSIOND_SOCKET=$SOCKET" \
    -e "PI_WEB_PORT=$PORT" >/dev/null; then
    return 0
  fi
  if holder_pids | grep -qx "$1"; then
    process_records "$1" | grep -E "dist/server/(sessiond|index)\.js" >/dev/null
    return $?
  fi
  return 1
}

# Pids that hold this stack's unix socket or TCP port. The daemon owns only the
# socket (no TCP), so a port scan alone never sees it; asking lsof who holds
# each resource needs no environment visibility at all.
holder_pids() {
  # lsof exits 1 when it matches nothing, which under `set -e` + pipefail killed
  # this script silently the moment the stack was already down - the failure
  # looked like "up does nothing". Absence of a holder is an answer, not an error.
  { lsof -t -- "$SOCKET" 2>/dev/null || true; lsof -nP -tiTCP:"$PORT" -sTCP:LISTEN 2>/dev/null || true; } | sort -u
}

# The daemon hosting the session that runs this script is an ancestor of it.
# Refusing ancestors keeps that daemon unkillable here by construction.
is_ancestor_of_self() {
  local pid="$$"
  while [ -n "$pid" ] && [ "$pid" -gt 1 ] 2>/dev/null; do
    if [ "$pid" = "$1" ]; then return 0; fi
    pid="$(ps -p "$pid" -o ppid= 2>/dev/null | tr -d ' ')"
  done
  return 1
}

marked_pids() {
  if has_proc; then
    local environ pid
    for environ in /proc/[0-9]*/environ; do
      pid="${environ#/proc/}"
      pid="${pid%/environ}"
      if [ "$pid" = "$$" ]; then continue; fi
      if { tr '\0' '\n' <"$environ"; } 2>/dev/null | grep -Fx -e "PI_WEB_DATA_DIR=$DATA_DIR" -e "PI_WEB_SESSIOND_SOCKET=$SOCKET" >/dev/null; then
        echo "$pid"
      fi
    done
    return 0
  fi
  ps -Axww -E -o pid=,command= 2>/dev/null \
    | grep -F -e "PI_WEB_DATA_DIR=$DATA_DIR" -e "PI_WEB_SESSIOND_SOCKET=$SOCKET" \
    | awk '{print $1}' | sort -u
}

port_pids() {
  { lsof -nP -iTCP:"$PORT" -sTCP:LISTEN -t 2>/dev/null || true; } | sort -u
}

stack_pids() {
  { marked_pids; port_pids; holder_pids; } | sort -u
}

report_pids() {
  local pid
  for pid in $(stack_pids); do
    printf '  pid %-7s %s\n' "$pid" "$(ps -p "$pid" -o command= 2>/dev/null | cut -c1-80)"
  done
}

wait_for_session_gone() {
  local name="$1"
  local waited=0
  while tmux has-session -t "$name" 2>/dev/null; do
    if [ "$waited" -ge 10 ]; then
      echo "FAIL: tmux session $name still exists after kill-session" >&2
      exit 1
    fi
    sleep 1
    waited=$((waited + 1))
  done
}

stop_stack() {
  local pids doomed pid
  pids="$(stack_pids)"
  if [ -z "$pids" ]; then
    echo "no previous 8505 processes"
    return 0
  fi
  doomed=""
  for pid in $pids; do
    # A pid from the lsof/ps snapshot can be gone by the time we ask about it.
    # An empty command line is a dead process, not a stranger: skip it rather
    # than refusing - refusing turned "unreadable" into "unauthorised" once.
    if [ -z "$(process_command_line "$pid")" ]; then
      continue
    fi
    if is_ancestor_of_self "$pid"; then
      echo "REFUSED: pid $pid is an ancestor of this script; not killing anything" >&2
      exit 1
    fi
    if ! is_8505_process "$pid"; then
      echo "REFUSED: pid $pid holds port $PORT but its command line has no 8505 marker" >&2
      echo "         $(process_command_line "$pid" | cut -c1-160)" >&2
      exit 1
    fi
    doomed="$doomed $pid"
  done
  echo "stopping previous 8505 processes:$doomed"
  # shellcheck disable=SC2086
  kill -TERM $doomed 2>/dev/null || true
  local waited=0
  while [ "$waited" -lt 15 ]; do
    if [ -z "$(stack_pids)" ]; then break; fi
    sleep 1
    waited=$((waited + 1))
  done
  for pid in $(stack_pids); do
    if is_8505_process "$pid" && ! is_ancestor_of_self "$pid"; then
      echo "pid $pid did not stop on TERM; sending KILL"
      kill -KILL "$pid" 2>/dev/null || true
    fi
  done
  # tmux windows are killed by name, and only the two this script owns.
  tmux kill-session -t "$SESSIOND_TMUX" 2>/dev/null || true
  tmux kill-session -t "$WEB_TMUX" 2>/dev/null || true
  # kill-session returns before the session is gone, and the next start then
  # died on "duplicate session" while a healthy stack was still answering 200 -
  # a script that reports failure over a working service teaches you to ignore
  # its exit code.
  wait_for_session_gone "$SESSIOND_TMUX"
  wait_for_session_gone "$WEB_TMUX"
  # A dead daemon leaves its socket file behind, and a stale socket file makes
  # "the socket exists" - which start_stack waits on - true before the new
  # daemon ever binds. Remove it only once nothing holds it.
  if [ -S "$SOCKET" ] && [ -z "$(lsof -t -- "$SOCKET" 2>/dev/null)" ]; then
    rm -f -- "$SOCKET"
  fi
}

start_stack() {
  mkdir -p "$DATA_DIR" "$DATA_DIR/logs"
  # The daemon has died after READY more than once, and its output lived only
  # in the tmux pane - killed pane, lost cause. Every run appends to a log so a
  # crash leaves evidence; the pane stays for interactive watching.
  tmux new-session -d -s "$SESSIOND_TMUX" -c "$REPO_ROOT" \
    "${CONFIG_ENV}${AGENT_ENV}PI_WEB_DATA_DIR=$DATA_DIR PI_WEB_SESSIOND_SOCKET=$SOCKET PI_WEB_UI_CUSTOM_PROBE=${PI_WEB_UI_CUSTOM_PROBE:-1} PI_WEB_DEBUG_EXTENSION_PATHS=$REPO_ROOT/test-fixtures/pi-extensions/ui-custom-probe.ts PI_WEB_DEBUG_FRAME_DROP=${PI_WEB_DEBUG_FRAME_DROP:-0} PI_WEB_DEBUG_PROMPT_CAPTURE=${PI_WEB_DEBUG_PROMPT_CAPTURE:-0} node dist/server/sessiond.js 2>&1 | tee -a $DATA_DIR/logs/sessiond.log"
  tmux set-option -t "$SESSIOND_TMUX" remain-on-exit on >/dev/null
  local waited=0
  while [ ! -S "$SOCKET" ]; do
    if [ "$waited" -ge 30 ]; then
      echo "FAIL: session daemon socket $SOCKET never appeared" >&2
      tmux capture-pane -p -t "$SESSIOND_TMUX" | tail -20 >&2
      exit 1
    fi
    sleep 1
    waited=$((waited + 1))
  done
  tmux new-session -d -s "$WEB_TMUX" -c "$REPO_ROOT" \
    "${CONFIG_ENV}${AGENT_ENV}PI_WEB_DATA_DIR=$DATA_DIR PI_WEB_SESSIOND_SOCKET=$SOCKET PI_WEB_PORT=$PORT node dist/server/index.js 2>&1 | tee -a $DATA_DIR/logs/web.log"
  tmux set-option -t "$WEB_TMUX" remain-on-exit on >/dev/null
}

# 200 alone proves someone is serving, not that OUR freshly started processes
# are. A previous stack adopted this way once: the new daemon died on a bind
# conflict, the old one answered the health check, and the check ran against
# stale code. Identity, not liveness: the socket and port holders must be the
# processes the tmux sessions just started (or their descendants).
assert_started_identity() {
  local holder ok pane_pids
  pane_pids="$(tmux list-panes -s -t "$SESSIOND_TMUX" -F '#{pane_pid}' 2>/dev/null; tmux list-panes -s -t "$WEB_TMUX" -F '#{pane_pid}' 2>/dev/null)"
  for holder in $(holder_pids); do
    ok=0
    local pid="$holder"
    while [ -n "$pid" ] && [ "$pid" -gt 1 ] 2>/dev/null; do
      if echo "$pane_pids" | grep -qx "$pid"; then ok=1; break; fi
      pid="$(ps -p "$pid" -o ppid= 2>/dev/null | tr -d ' ')"
    done
    if [ "$ok" != "1" ]; then
      echo "FAIL: pid $holder holds this stack's socket/port but was not started by this invocation" >&2
      echo "      $(process_command_line "$holder" | cut -c1-160)" >&2
      echo "      a previous stack survived stop_stack; refusing to adopt it" >&2
      exit 1
    fi
  done
}

# A web/API with tls configured refuses plain HTTP at the connection (000); it is then asked over
# HTTPS on the same port, without verifying a certificate that names the machine, not 127.0.0.1.
http_status() {
  local code
  code="$(curl -sS -o /dev/null -w '%{http_code}' --max-time 5 "$1" 2>/dev/null)" || code=000
  if [ "$code" = "000" ]; then
    code="$(curl -ksS -o /dev/null -w '%{http_code}' --max-time 5 "https://${1#http://}" 2>/dev/null)" || code=000
  fi
  echo "$code"
}

wait_until_ready() {
  local waited=0 app health
  while [ "$waited" -lt "$READY_TIMEOUT_SECONDS" ]; do
    app="$(http_status "$BASE_URL/")"
    health="$(http_status "$BASE_URL/api/sessiond/health")"
    if [ "$app" = "200" ] && [ "$health" = "200" ]; then
      assert_started_identity
      return 0
    fi
    sleep 1
    waited=$((waited + 1))
  done
  echo "FAIL: 8505 did not answer 200 within ${READY_TIMEOUT_SECONDS}s (app=$app health=$health)" >&2
  tmux capture-pane -p -t "$WEB_TMUX" 2>/dev/null | tail -20 >&2
  tmux capture-pane -p -t "$SESSIOND_TMUX" 2>/dev/null | tail -20 >&2
  exit 1
}

command_up() {
  if [ "${1:-}" != "--skip-build" ]; then
    echo "building..."
    (cd "$REPO_ROOT" && pnpm run build >/dev/null)
  else
    echo "skipping build"
  fi
  stop_stack
  start_stack
  wait_until_ready
  echo "8505 processes:"
  report_pids
  echo "tmux sessions: $SESSIOND_TMUX (daemon), $WEB_TMUX (web/API)"
  echo "READY: $BASE_URL answers 200, session daemon healthy on $SOCKET"
}

command_status() {
  local pids
  pids="$(stack_pids)"
  if [ -z "$pids" ]; then
    echo "8505 stack: not running"
  else
    echo "8505 processes:"
    report_pids
  fi
  echo "app    $BASE_URL/                    -> $(http_status "$BASE_URL/")"
  echo "daemon $BASE_URL/api/sessiond/health -> $(http_status "$BASE_URL/api/sessiond/health")"
}

case "${1:-up}" in
  up) command_up "${2:-}" ;;
  down) stop_stack ;;
  status) command_status ;;
  -h | --help | help) usage ;;
  *)
    echo "unknown command: $1" >&2
    usage >&2
    exit 2
    ;;
esac
